export class OnboardingError extends Error {
  constructor(code) {
    const safeCode =
      typeof code === 'string' && /^[A-Z0-9_]+$/.test(code) ? code : ERROR_CODES.ONBOARDING_FAILED;
    super(safeCode);
    this.name = 'OnboardingError';
    this.code = safeCode;
  }
}

/** Convert any error to a fixed code without ever reading its message. */
export function safeErrorCode(error, fallback = ERROR_CODES.ONBOARDING_FAILED) {
  if (error && typeof error.code === 'string' && /^[A-Z0-9_]+$/.test(error.code)) {
    return error.code;
  }
  return fallback;
}
